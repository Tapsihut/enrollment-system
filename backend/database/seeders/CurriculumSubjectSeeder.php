    /*
    |--------------------------------------------------------------------------
    | ASSIGN SUBJECTS TO CURRICULUM
    |--------------------------------------------------------------------------
    */

    private function assignSubjects(
        Curriculum $curriculum,
        array $assignments,
        string $curriculumName
    ): void {

        foreach ($assignments as $code => $placement) {

            [$yearLevel, $semester] = $placement;


            /*
            |--------------------------------------------------------------------------
            | Find Subject
            |--------------------------------------------------------------------------
            */

            $subject = Subject::where('code', $code)->first();


            if (!$subject) {

                $this->command->warn(
                    "Subject not found in {$curriculumName}: {$code}"
                );

                continue;
            }


            /*
            |--------------------------------------------------------------------------
            | Create / Update Curriculum Subject
            |--------------------------------------------------------------------------
            */

            CurriculumSubject::updateOrCreate(

                [
                    'curriculum_id' => $curriculum->id,
                    'subject_id'    => $subject->id,
                ],

                [
                    'year_level' => $yearLevel,
                    'semester'   => $semester,
                ]

            );


            $this->command->info(
                "{$curriculumName}: {$code} → Year {$yearLevel}, Semester {$semester}"
            );
        }


        $this->command->info(
            "{$curriculumName} curriculum subjects assigned successfully."
        );
    }
